// 可交易个股宇宙：《投资总策略》第一章交易权限——个股仅沪深主板可交易。
// 创业板（300/301）、科创板（688）、北交所/新三板（4/8/9 等）不得进入个股信号或排名。
// 任何服务端扫描、排名和关注写入都应复用同一口径，避免策略正文与实现再次漂移。
// ETF 不受个股板块权限限制，不走此判断。
export const TRADEABLE_STOCK_CODE_PATTERN = "^(600|601|603|605|000|001|002|003)";

/** 完整代码（含 .SH/.SZ）是否属于可交易的沪深主板个股。 */
export function isTradeableStockCode(code: string): boolean {
  return /^(?:600|601|603|605|000|001|002|003)\d{3}\.(?:SH|SZ)$/u.test(code);
}
