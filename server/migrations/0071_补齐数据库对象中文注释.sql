DO $$
DECLARE
  missing_names text;
  item record;
BEGIN
  SELECT string_agg(c.relname, ', ' ORDER BY c.relname)
    INTO missing_names
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN _table_comment description ON description.object_name = c.relname
   WHERE n.nspname = 'public'
     AND c.relkind IN ('r', 'p')
     AND description.object_name IS NULL;
  IF missing_names IS NOT NULL THEN
    RAISE EXCEPTION '数据库表注释词典缺少：%', missing_names;
  END IF;

  FOR item IN
    SELECT c.oid, c.relname, description.description
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      JOIN _table_comment description ON description.object_name = c.relname
     WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
  LOOP
    IF obj_description(item.oid, 'pg_class') IS NULL THEN
      EXECUTE format('COMMENT ON TABLE public.%I IS %L', item.relname, item.description);
    END IF;
  END LOOP;
END $$;

