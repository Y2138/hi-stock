DECLARE
  missing_names text;
  item record;
BEGIN
  SELECT string_agg(name, ', ' ORDER BY name)
    INTO missing_names
    FROM (
      SELECT DISTINCT attribute.attname AS name
        FROM pg_class relation
        JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
        JOIN pg_attribute attribute
          ON attribute.attrelid = relation.oid
         AND attribute.attnum > 0
         AND NOT attribute.attisdropped
        LEFT JOIN _column_comment description ON description.column_name = attribute.attname
       WHERE namespace.nspname = 'public'
         AND relation.relkind IN ('r', 'p')
         AND description.column_name IS NULL
    ) missing;
  IF missing_names IS NOT NULL THEN
    RAISE EXCEPTION '数据库字段注释词典缺少：%', missing_names;
  END IF;

  FOR item IN
    SELECT relation.oid, relation.relname, attribute.attnum, attribute.attname,
           description.description
      FROM pg_class relation
      JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
      JOIN pg_attribute attribute
        ON attribute.attrelid = relation.oid
       AND attribute.attnum > 0
       AND NOT attribute.attisdropped
      JOIN _column_comment description ON description.column_name = attribute.attname
     WHERE namespace.nspname = 'public' AND relation.relkind IN ('r', 'p')
  LOOP
    IF col_description(item.oid, item.attnum) IS NULL THEN
      EXECUTE format(
        'COMMENT ON COLUMN public.%I.%I IS %L',
        item.relname,
        item.attname,
        item.description
      );
    END IF;
  END LOOP;
END $$;
