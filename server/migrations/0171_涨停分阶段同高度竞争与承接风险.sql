## 一、范围与时点

仅扫描沪深主板、非ST、非未开板新股、目标日收盘涨停的股票，不受个人标的池限制。候选资格所需连板数、封单、成交额、首次封板与价格形态缺失时不猜测；其他历史或消息缺口逐项保留。

