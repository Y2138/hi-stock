## 二、叙事与题材

同义词采用固定规则归一，出版发行、图书发行、教科书发行等合并为出版传媒；风电表达归一。控制权变更、资产重组可作为独立交易叙事保留，不能作为已核实利好。

保留多个驱动，同一标的近五个交易日仍有效标签的连续性优先，再比较当日宽度及名称；不因每日涨停原因文字变化随意切换主驱动。题材宽度、持续性和晋级率仅作背景，未知不当成充分证据。涨停原因必须与公告事实分开。

## 三、三个阶段与两条路线

- 首板：比较催化新旧、个股辨识度、首次封板和剩余买单覆盖，不因热门板块宽而自动提级。
- 二至三板确认：比较前一板至今的承接、同高度竞争者和题材核心状态。
- 四板及以上续板：重点观察高位放量弱封、断板负反馈和异常波动/停牌风险，不依靠历史涨幅提级。

抱团路线保留二板及以上的题材最高板候选；主升路线侧重首板至三板的启动与确认。两路线各最多两只、合并最多四只，先列各路线数据首位；同股重复只计一次。二至三板确认、首板、高位续板分别展示，不能把旧分直接跨阶段比较。双路线标签只说明兼具两种风格，不等于独立胜率共振或全场第一。

## 四、数据风险与比较顺序

