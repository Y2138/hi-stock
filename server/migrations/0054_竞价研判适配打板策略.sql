# 集合竞价机会研判

目标：依据本轮系统提示词注入的当前最终策略、目标交易日的最终集合竞价数据和最新有效每日计划，评估真实持仓的竞价应对、近期关注的开盘风险，并复核结构化池外机会。任务只生成研究结论，不执行交易，不修改持仓、标的池、近期关注、策略或任务定义；完整结果由系统关联本次运行保存到 `job_run_output`，池外机会判断在任务成功后更新到“今日池外机会”。

## 策略与时间口径

1. 当前已发布策略正文是信号定义、阈值、等级、验证状态和允许动作的唯一依据。不得沿用历史提示词中的候选门禁、评级或执行方式，也不得自行调整策略参数。
2. 对打板候选统一使用 T/T+1 口径：T 日收盘后生成信号，本任务目标交易日为 T+1 日，09:25 最终竞价数据就绪后只做竞价复核，不在竞价阶段重新评分或从全市场补选股票。
3. 打板候选只接受当前《打板策略》在 T 日形成的有效信号。T 日是否一字板不是统一候选门禁；必须保留当前策略给出的精确信号等级、抱团分、主升分、两条路线是否成立及各自名次。
4. 当前《打板策略》处于前向验证期时，打板候选即使得到竞价确认，系统结论也只能是“继续观察”，不得写成“值得入场”、买入建议或已成交事实。

## 日期与计划门禁

1. 先按需使用 `database_schema` 与 `database_query` 查询 `market_trading_day`。本次任务目标日必须存在且 `is_open=true`；非交易日直接输出“休市，不执行竞价研判”，交易日历缺失时列为数据缺口并停止，不得按工作日猜测。
2. 在交易日历中找到目标日前一个开市日，记为 T 日；目标日记为 T+1 日。查询最新一份状态有效的每日计划 `job_run_output`，并读取其已激活 `daily_plan_playbook`。
3. 每日计划的 `target_date` 不得早于 T 日且必须早于 T+1 日。更旧或日期不早于 T+1 日的计划无效：保留计划日期与缺口说明，但不得对其中池外机会给出有效判断；不得改用历史计划或重新发散选股。

## 候选范围

1. 真实持仓：`portfolio_position.quantity>0` 的全部标的，并读取同一每日计划中对应的 `position_action`、集合竞价预案和失效条件。
2. 近期关注：当前有效 `pool_membership` 中在 T+1 日仍处于关注期的全部标的，保留池别、角色、关注原因和关注起止日。已持仓标的只在持仓部分出现一次。
3. 池外机会：最新有效每日计划中按 `priority` 排序的全部结构化 `off_pool_opportunity`。与当前持仓或当前池成员冲突时标记数据异常，不按池外机会判断。
4. 对打板类池外机会，从每日计划正文及结构化行读取股票代码、名称、主标签、精确信号等级、抱团分、主升分、路线成立情况、路线名次、关键得分项、风险标记和失效条件。结构化 `grade` 只作兼容展示，不能替代当前《打板策略》的精确信号等级；上述关键信号信息无法确认时标记“数据不足”，不得根据普通 A/B/C 评级反推。

## 竞价数据

1. 先调用 `fetch_hithink_data` 获取 `auction_short_term_benchmark`，参数 `date` 使用 T+1 日。
2. 对全部候选代码调用 `auction_snapshot`，`stage='final'`；单批不超过 100 只，需要时分批。必须核对响应日期、`auction_phase`、`data_status`、数据时间和返回标的覆盖。
3. `data_status` 不是 `ready`、竞价阶段不是 `final`、返回为空、日期不一致或标的缺失时，逐项列为数据缺口。不得用实时行情、旧快照、盘中涨幅或模型常识补造竞价字段和结论。
4. 打板复核必须取得相对 T 日收盘的竞价涨跌幅、T+1 日涨停价、买卖方向明确的未匹配量、竞价换手率和停牌/异常状态。任一关键字段缺失即为“数据不足”；竞价成交额、昨日量比、竞价量比和短线风向标只能作为辅助证据。

## 判断规则

### 打板类池外机会

逐只按以下顺序形成且只形成一个 T+1 复核分类：

1. **数据不足**：计划中的有效信号信息或竞价关键字段缺失、数据未最终就绪、日期不一致。
2. **放弃**：跌停开盘、停牌或不可执行异常；买方未匹配量小于等于 0；竞价换手率超过当前策略上限。
3. **延续确认·一字排队观察**：竞价价格达到 T+1 涨停价、买方未匹配量大于 0、竞价换手率不超过当前策略上限，且数据完整。该分支优先于非一字的涨幅限制；确认只表示一字延续，不表示排队可成交或可获得理论收益。
4. **放弃**：未达到涨停价且相对 T 日收盘的竞价涨幅超过当前策略允许上限，不追高。
5. **延续确认·换手晋级观察**：竞价未达到涨停价、涨幅位于当前策略允许区间、买方未匹配量大于 0、竞价换手率不超过当前策略上限，且 T 日信号等级允许换手晋级。不得因未顶一字直接淘汰该分支。
6. **分歧观察**：竞价低于 T 日收盘但买方未匹配量仍大于 0；只满足抱团路线的候选未顶一字但没有明显卖方堆积；或竞价方向与题材、连板、市场结构证据不一致。
7. 以上分支均不满足时，按当前策略的失效条件判断“放弃”；不得使用主观强弱、接近阈值或盘中冲板预期升级结论。

当前《打板策略》处于前向验证期时，结构化结论固定映射为：一字延续确认、换手晋级确认、分歧观察使用 `observe`；放弃使用 `give_up`；数据不足使用 `unavailable`。不得对打板候选使用 `worth_entering`。

### 持仓、近期关注与其他池外机会

1. 真实持仓只判断“按原预案执行”“竞价转弱，升级风险”“数据不足”，说明竞价表现与原 `position_action` 是否一致；不得自行新增卖出、减仓或加仓动作。
2. 近期关注和非打板类池外机会按各自适用的当前策略、原计划证据、尚缺条件和失效条件判断。高开、放量、未匹配量或短线风向标都只能作为证据，任何单项不得等同于买入条件。
3. 只有适用策略已明确允许入场、完整条件全部满足且不处于观察或验证状态时，非打板类池外机会才可使用“值得入场”；仍须完成现有新标的完整入池评估并由用户确认。本任务不得自动买入、自动入池或自动标记近期关注。

