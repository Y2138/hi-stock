## 二、右侧与试盘评估（不开仓）

### 2.1 右侧条件存活复核

右侧主升六条件：DIF>0；MA20高于前一交易日；MACD柱>0且单日增量/收盘价>0.001；收盘价>MA5>MA10；收盘相对开盘涨幅≥1%；成交量>5日均量×1.2。

每日对持仓与关注标的重算六条件存活数 m：

- m≤2（存活不超过2项）且该持仓尚未触发一档止盈时，为崩坏信号，支撑“下一交易日开盘退出”的预案判断；
- 买入后第5个交易日收盘仍未触发一档止盈的持仓，按时间兜底提示退出；
- m 越高说明趋势结构越完整，是“继续持有”判断的主要量化依据。

### 2.2 试盘形态概率评估

试盘“试盘日→缩量回调→放量突破”形态：近10个交易日内存在试盘日（成交量>VMA5×1.2且上影线>收盘价×2%）；之后至少间隔2个交易日缩量回调不破试盘日低点；当前出现放量突破试盘高点。

形态推进越完整，标的后续上涨概率评估越高；它只用于关注标的的概率判断与预案强度，不构成开仓信号，也不单独写入关注。

