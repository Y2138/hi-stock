## 四、共同成交边界

- 日线策略只使用当日及此前已经确认的数据，禁止前视。
- T日收盘信号最早T+1成交；A股个股买入当日不得卖出。
- T+1盘中确认执行：T日收盘评估产生的观察候选（除价格触发类条件外其余条件已全部满足的标的），自下一交易日起进入盘中确认状态；当日盘中价格满足触发条件时，即视为信号满足，可按触发价加滑点买入，并按信号样本归因。观察候选的有效期与收盘信号一致，仅为下一交易日内有效。
- 收盘产生的信号自下一交易日起按其设定触发价位持续有效：次日盘中价格最先满足触发条件时执行；卖出类信号若开盘已越过触发价位，以开盘价直接执行并登记执行符合度。
- 未设触发价位的时间型退出（时间兜底、观察期到期、止损位切换生效日等）在下一交易日开盘执行。
- 日内硬止损按对应策略规则执行。
- 成交必须计入滑点、佣金、印花税、过户费和100股整数约束。
- 每个标的的持仓按其入场信号类型记录评估口径，不得混用不同信号类型的退出口径。
- 同日候选超过资金容量时，只按对应策略定义的排序执行，不为提高资金利用率放宽信号。

