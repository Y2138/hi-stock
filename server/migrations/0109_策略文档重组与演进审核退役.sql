## 三、市场状态调度

市场状态由同花顺一级行业板块指数（`market_bar` 中 881 前缀 `.TI` 日线，板块集合随 `market_board` 目录动态增减）的等权日收益构成综合指数，再使用同一套短期指标判断：MA5>MA20且ROC5>0为牛市，MA5<MA20且ROC5<0为熊市，其余为震荡。该状态同时用于信号环境、新开仓仓位系数和最大持仓数。

> **板块构成边界**：市场状态与全市场温度使用一级行业（881 前缀）全集等权；二级行业（884 前缀）与概念、区域、特色板块仅作个股归属、下钻与解释，不进入温度与状态合成。板块日线由 `daily_data_update` 日更，板块目录以 `market_board` 为准。

状态只调整新开仓额度和最大持仓数，不自动清仓已有合规持仓，也不降低任何信号的质量门槛。各任务的入场与评估条件在牛市、震荡和熊市中**完全相同**，市场状态不改变信号判定标准，只改变仓位系数与最大持仓数。

| 市场状态 | 新开仓额度 | 最大同时持仓 |
|----------|-----------|--------------|
| 牛市 | ×1.00 | 6只 |
