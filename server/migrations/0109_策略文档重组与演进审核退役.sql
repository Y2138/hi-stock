## 二、资金与组合约束

### 2.1 开仓通道

系统的唯一量化开仓信号是波段信号（见《每日计划策略》）；打板机会仅作观察，不自动开仓；右侧主升、试盘启动与左侧反转不再产生新开仓，对应存量持仓按各自退出口径管理至清零，不得因清零目标放宽任何退出条件。

- 新开仓额度上限：当前权益的 100%，并受现金、行业集中度、单笔风险预算、市场状态系数与 100 股整数约束取最小值。
- 市场状态系数与最大同时持仓数按波段档执行：牛市额度×1.00 最多 6 只；震荡额度×1.00 最多 5 只；熊市额度×0.80 最多 4 只。
- 单只额度按标的分级乘数计算（基准以初始权益 20 万元标定，随当前权益同比缩放）：S 46,800 元、A 23,400 元、B 12,480 元。
- 新标的经用户确认入池时，必须同步进入正式集合，不设置池内观察期。

标的分级在每季度首日计算并在季度内冻结：优先使用季初前两个完整季度的已完成交易；若该窗口没有任何已完成交易，则整段顺延到再前两个完整季度；顺延后仍无样本才按样本不足归B。正式等级只使用S/A/B，不设置星号等临时等级：

- S：总盈亏>8,000元，或胜率>58%且交易数≥10；
- A：总盈亏3,000-8,000元，或胜率50%-58%；
- B：其余标的或样本不足。

### 2.2 单只仓位与组合硬约束

单笔权益风险上限 `2.0%`。使用低于上限的仓位属于保守执行，不构成规则冲突；但不得把保守实盘结果直接等同于回测收益。

| 约束 | 上限 |
|------|------|
| 单只标的市值 | 当前权益50% |
| 同行业持仓 | 2只 |
| 单笔计划亏损 | 当前权益2.0% |
| 交易单位 | 100股整数倍 |
| 融资与负现金 | 禁止 |

- 现金没有固定比例下限；无合格信号时自然持币，有信号时可以接近满仓，但必须保留成交费用。
- 配置比例是上限，不是必须完成的持仓目标。
- 最近126个自然日的已完成交易只用于小幅调整标的分级，不使用未来交易。

