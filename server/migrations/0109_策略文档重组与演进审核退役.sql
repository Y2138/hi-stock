## 一、波段开仓（唯一正式信号）

T日收盘必须同时满足：

1. 成交量<5日均量×0.85；
2. 阳线，或下影线>收盘价0.5%；
3. RSI14<40；
4. 以近40日箱顶×0.95为目标、以初始弹性止损为风险，预期盈亏比≥1.8。

二次探底、MACD、MA20/MA60位置和板块温度都不是波段硬条件。

T+1必须突破T日最高价，确认成交价不得高于T日收盘价5%；未突破或确认价过高均放弃。确认既可在T+1开盘完成，也可在盘中价格首次突破T日最高价时按盘中确认买入（成交价≤T日收盘价×1.05），两种方式效力相同。一次建仓，不自动补仓。

### 1.1 初始止损与观察期

初始弹性止损按股性选择：

```text
护盘收回率≥50%：买入价×0.90
护盘收回率<50%：买入价×0.93
箱体边界：近20日最低价×0.97
初始止损：min(买入价×0.99, max(股性止损, 箱体边界))
```

ETF无个股股性数据，初始止损仅取箱体边界分支。

买入后前10个交易日为观察期，实际止损暂设为买入价×0.75；第11个交易日起恢复上述初始止损。该-25%位置是观察期灾难保护，不得被描述成常规波段止损。

### 1.2 箱顶止盈与到期

- 价格达到原箱顶×0.95时卖出剩余仓位的一半，按100股取整；
- 未形成有效突破时，持有满60个交易日，下一交易日开盘退出；
- 箱顶减仓后，收盘浮盈≥8%把保护位提高到买入价，≥15%提高到买入价+5%；浮盈>5%时同时参考MA20×0.98；
- 日内同时触及止损和箱顶目标时按先止损的保守顺序处理。

### 1.3 突破后移动止盈

收盘高于原箱顶且成交量>20日均量×1.2，认定箱体突破。突破后3个交易日保留缓冲；之后：

- MA10跌破收回率≥50%：取“最高收盘-2.8×ATR14”和“MA10×0.98”的较高者；
- 其余标的：取“最高收盘-3.5×ATR14”和“MA20×0.97”的较高者。

突破后的剩余仓位取消60日到期，直到移动止盈触发。移动止盈只能上移，不能向下放宽。

